"""
mock_gateway.py  |  Thin FastAPI wrapper around mock_core.py (tasks 4.1 to 4.3). SIMULATION ONLY.

Run:   python -m uvicorn mock_gateway:app --app-dir src --port 8000
Docs:  http://127.0.0.1:8000/docs   (Swagger page generated by FastAPI)
Needs: pip install fastapi uvicorn httpx
"""
import os
from typing import Optional, Union

from fastapi import Body, FastAPI, Header, HTTPException
from pydantic import BaseModel

from mock_core import Hub, MockWallet, WalletError

HERE = os.path.dirname(os.path.abspath(__file__))
PARTICIPANTS = os.environ.get("MOCK_PARTICIPANTS", os.path.join(HERE, "participants.yaml"))

app = FastAPI(title="Mock Orange Money wallet + interoperability hub (SIMULATION)",
              description="Synthetic data only. Not Orange's API and not a licensed payment system.", version="1.0")
wallet = MockWallet()
hub = Hub(PARTICIPANTS, wallet)


class PaymentRequest(BaseModel):
    merchant_key: str
    currency: str
    order_id: str
    amount: Union[int, float, str]
    return_url: str
    cancel_url: str
    notif_url: str
    lang: Optional[str] = "en"
    reference: Optional[str] = None


class StatusRequest(BaseModel):
    order_id: str
    amount: Union[int, float, str]
    pay_token: str


class CustomerAction(BaseModel):
    outcome: str = "SUCCESS"


def _raise(exc):
    raise HTTPException(status_code=exc.http_status, detail={"code": exc.code, "message": exc.message})


@app.get("/health")
def health():
    return {"status": "ok", "mode": "SIMULATION: mock wallet and hub, synthetic data only"}


@app.post("/mock/reset")
def reset():
    hub.reset()
    return {"status": "reset"}


@app.post("/oauth/v3/token")
def token(authorization: Optional[str] = Header(default=None)):
    try:
        return wallet.issue_token(authorization)
    except WalletError as exc:
        _raise(exc)


@app.post("/orange-money-webpay/dev/v1/webpayment", status_code=201)
def create_payment(body: PaymentRequest, authorization: Optional[str] = Header(default=None)):
    try:
        return wallet.create_payment(authorization, body.model_dump())
    except WalletError as exc:
        _raise(exc)


@app.post("/orange-money-webpay/dev/v1/transactionstatus")
def transaction_status(body: StatusRequest, authorization: Optional[str] = Header(default=None)):
    try:
        return wallet.status(authorization, body.model_dump())
    except WalletError as exc:
        _raise(exc)


@app.post("/mock/customer/pay/{pay_token}")
def customer_pay(pay_token: str, action: CustomerAction):
    try:
        return wallet.complete(pay_token, action.outcome)
    except WalletError as exc:
        _raise(exc)


@app.get("/mock/notifications")
def notifications():
    return wallet.notifications


@app.post("/interop/v1/bank-to-wallet")
def bank_to_wallet(raw: dict = Body(...), simulate: str = "SUCCESS"):
    try:
        result = hub.bank_to_wallet(raw, simulate)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc))
    if not result["accepted"]:
        raise HTTPException(status_code=result["http_status"], detail=result["reasons"])
    return result


@app.get("/interop/v1/payments/{end_to_end_id}")
def get_payment(end_to_end_id: str):
    found = hub.get_payment(end_to_end_id)
    if found is None:
        raise HTTPException(status_code=404, detail={"code": "NOT_FOUND", "message": "no such payment"})
    return found
